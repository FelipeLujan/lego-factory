"""ONE COMMAND BUILD for a TikTok explainer.   Run from the project folder:   python tools/build.py

What it does, in order (each step prints OK or a clear ERROR with the fix):
  1. Voice    : if script.json changed (or no voice yet) -> Google Cloud TTS (tools/tts.py) + word timings (tools/words.py)
  2. Captions : compositions/captions.html  (1-2 words per caption, accent colours from cues.json "accent")
  3. Cues     : resolves every spoken phrase in cues.json to seconds -> assets/cues.js
                generates compositions/hud.html (hook title, end card, flash frames, letter slams, name tags)
                sets the video length in index.html
  4. Sound    : mixes assets/sfx/sfx-bed.wav from cues.json + the curated library in assets/sfx/sounds.json
  5. Report   : length, every cue time, warnings, and the snapshot command to run next

Flags:  --voice   force a new voiceover even if script.json did not change
        --no-voice  never call TTS (use the existing voice)
DO NOT EDIT THIS FILE for a new video. Edit script.json, cues.json and assets/scene.js."""
import hashlib, html, json, math, os, re, subprocess, sys, wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
END_HOLD = 2.4      # seconds the end card holds after the last word
SR = 48000
FRAME = 1 / 30
problems = []

def die(msg):
    print("\nERROR: " + msg)
    sys.exit(1)

def load_json(rel):
    try:
        return json.load(open(P(rel), encoding="utf-8-sig"))
    except FileNotFoundError:
        die(f"{rel} is missing.")
    except json.JSONDecodeError as e:
        die(f"{rel} is not valid JSON: {e}. Fix the comma/quote at that line.")

def norm(w):
    return re.sub(r"[^a-z0-9']", "", w.lower().replace("’", "'"))

# ------------------------------------------------------------------ 1. voice
def step_voice(force, never):
    script = load_json("script.json")
    h = hashlib.sha1(json.dumps(script, sort_keys=True).encode()).hexdigest()[:12]
    vt_path = P("voice-timing.json")
    have = os.path.exists(P("assets", "voice", "voice.wav")) and os.path.exists(P("words.json")) and os.path.exists(vt_path)
    old_h = json.load(open(vt_path, encoding="utf-8")).get("script_hash") if os.path.exists(vt_path) else None
    if never:
        if not have:
            die("--no-voice was given but there is no voice yet. Run without --no-voice.")
        print("1. Voice    : reused (--no-voice)")
        return script
    if have and old_h == h and not force:
        print("1. Voice    : reused (script.json unchanged)")
        return script
    print("1. Voice    : generating with Google Cloud TTS ...")
    tok = subprocess.run("gcloud auth print-access-token", shell=True, capture_output=True, text=True).stdout.strip()
    if not tok:
        die("could not get a Google Cloud token. Run:  gcloud auth login   then try again.")
    project = script.get("gcp_project") or subprocess.run("gcloud config get-value project", shell=True, capture_output=True, text=True).stdout.strip()
    if not project:
        die('no Google Cloud project. Add "gcp_project": "<id>" to script.json.')
    r = subprocess.run([sys.executable, P("tools", "tts.py"), tok, project, script["voice"], str(script.get("rate", 1.1)), "0.05"], capture_output=True, text=True)
    if r.returncode != 0:
        die("TTS failed:\n" + r.stdout[-1500:] + r.stderr[-1500:] + "\nCheck the voice name in script.json (e.g. en-US-Chirp3-HD-Sadachbia).")
    print("             " + r.stdout.strip().splitlines()[-1])
    print("             transcribing word timings (faster-whisper, ~1 min) ...")
    r = subprocess.run([sys.executable, P("tools", "words.py")], capture_output=True, text=True, cwd=P("tools"))
    if r.returncode != 0 or not os.path.exists(P("words.json")):
        die("word timing failed:\n" + r.stderr[-2000:] + "\nIs faster-whisper installed?  python -m pip install --user faster-whisper")
    vt = json.load(open(vt_path, encoding="utf-8"))
    vt["script_hash"] = h
    json.dump(vt, open(vt_path, "w", encoding="utf-8"), indent=1)
    return script

# ------------------------------------------------------------------ 2. captions
def align(script):
    words = json.load(open(P("words.json"), encoding="utf-8"))
    toks = [{"w": w, "line": ln["id"]} for ln in script["lines"] for w in ln["text"].split()]
    if abs(len(toks) - len(words)) > 3:
        problems.append(f"script has {len(toks)} words but the voice transcript has {len(words)}; captions may drift. "
                        "Spell numbers as the voice says them, or ignore if captions look right.")
    # Global sequence alignment (difflib), so a mismatch like "thirty percent" vs "30%" or "de-icing" vs "de -icing"
    # never shifts the words after it. Script words with no exact partner get times interpolated between neighbours.
    import difflib
    key = lambda w: norm(w).replace("'", "").rstrip("s")
    a = [key(w["w"]) for w in words]
    b = [key(t["w"]) for t in toks]
    m = {}
    for blk in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
        for j in range(blk.size):
            m[blk.b + j] = blk.a + j
    i = 0
    while i < len(toks):
        if i in m:
            toks[i]["s"], toks[i]["e"] = words[m[i]]["s"], words[m[i]]["e"]
            i += 1
            continue
        j = i
        while j < len(toks) and j not in m:
            j += 1
        lo = words[m[i - 1]]["e"] if i > 0 else 0.0
        hi = words[m[j]]["s"] if j < len(toks) else words[-1]["e"]
        # whisper words that sit in the gap give the exact span when available
        ka = (m[i - 1] + 1) if i > 0 else 0
        kb = m[j] if j < len(toks) else len(words)
        if kb > ka:
            lo, hi = words[ka]["s"], words[kb - 1]["e"]
        n = j - i
        for k in range(n):
            toks[i + k]["s"] = lo + (hi - lo) * k / n
            toks[i + k]["e"] = lo + (hi - lo) * (k + 1) / n
        i = j
    for i in range(1, len(toks)):
        if toks[i]["s"] <= toks[i - 1]["s"]:
            toks[i]["s"] = toks[i - 1]["s"] + 0.08
    return toks

def rnd(n):
    x = math.sin(n * 127.1 + 311.7) * 43758.5453
    return x - math.floor(x)

def step_captions(toks, cues):
    accent = {norm(a) for a in cues.get("accent", [])}
    # SUBTITLE MODE (cues.json "captions": {"style": "subtitle", "max_words": 4, "max_chars": 26}): small sentence-case
    # lower-third lines of 3-4 words, like documentary Shorts. Default (no key) = the house style: huge 1-2 word captions.
    cap = cues.get("captions", {}) or {}
    sub = cap.get("style") == "subtitle"
    maxw, maxc = (cap.get("max_words", 4), cap.get("max_chars", 26)) if sub else (2, 12)
    groups, cur = [], []
    for i, t in enumerate(toks):
        if cur and len(" ".join(x["w"] for x in cur + [t])) > maxc:
            groups.append(cur); cur = []
        cur.append(t)
        nxt = toks[i + 1] if i + 1 < len(toks) else None
        if re.search(r"[.,:;?!]$", t["w"]) or nxt is None or nxt["line"] != t["line"] or len(cur) >= maxw:
            groups.append(cur); cur = []
    if cur:
        groups.append(cur)
    rows, beats, accs, n_acc = [], [], [], 0
    for gi, g in enumerate(groups):
        start = g[0]["s"]
        end = min(groups[gi + 1][0]["s"], g[-1]["e"] + 0.45) if gi + 1 < len(groups) else g[-1]["e"] + 0.6
        end = max(end, start + 0.25)
        if gi + 1 < len(groups):
            end = min(end, groups[gi + 1][0]["s"])
        acc = next((x for x in reversed(g) if norm(x["w"]) in accent), None)
        cls = ""
        if acc is not None:
            cls = "acc" if n_acc % 2 == 0 else "acc2"
            n_acc += 1
            accs.append(round(start, 3))
        parts = []
        for x in g:
            w = html.escape((x["w"].rstrip(".,;") if sub else x["w"].rstrip(".,:;?!").upper()).replace("’", "'"), quote=False)
            parts.append(f'<span class="{cls}">{w}</span>' if x is acc else w)
        txt = " ".join(parts)
        n = len(re.sub("<[^>]+>", "", txt))
        fs = (58 if n <= 22 else 50) if sub else (100 if n <= 8 else (84 if n <= 10 else 72))
        rows.append(f'    <div id="cap-{gi:03d}" class="clip cap" data-start="{round(start, 3)}" data-duration="{round(end - start, 3)}" '
                    f'data-track-index="1" data-rot="{0 if sub else round((rnd(gi) - 0.5) * 7, 2)}" data-acc="{0 if sub else (1 if acc else 0)}">'
                    f'<span class="cap-in" style="font-size:{fs}px">{txt}</span></div>')
        beats.append(round(start, 3))
    doc = CAPTIONS_HTML.replace("%ROWS%", "\n".join(rows))
    if sub:  # lower third, lighter outline, gentle pop (no tilt, no big scale-in)
        doc = doc.replace("top: 1070px; height: 150px;", "top: 1395px; height: 130px;").replace("-webkit-text-stroke: 11px #000;", "-webkit-text-stroke: 9px #000;").replace("text-shadow: 0 8px 0 rgba(0, 0, 0, 0.85);", "text-shadow: 0 5px 0 rgba(0, 0, 0, 0.8);")
        doc = doc.replace("{ scale: big ? 1.6 : 1.3, rotation: rot * 2.2, y: 26 }", "{ scale: 1.08, rotation: 0, y: 10 }")
    open(P("compositions", "captions.html"), "w", encoding="utf-8").write(doc)
    print(f"2. Captions : {len(rows)} captions, {len(accs)} accent words")
    if not accs:
        problems.append('no caption got an accent colour: add key words from the script to cues.json "accent".')
    return beats, accs

# ------------------------------------------------------------------ 3. cues
def find(toks, phrase, nth=1, after=-1, what=""):
    want = [norm(w) for w in str(phrase).split() if norm(w)]
    seen = 0
    for i in range(len(toks) - len(want) + 1):
        if all(norm(toks[i + j]["w"]) == want[j] for j in range(len(want))):
            seen += 1
            if seen == nth:
                return toks[i]["s"], i
    problems.append(f'{what}: the phrase "{phrase}" (nth={nth}) is not in the script. Use words exactly as written in script.json.')
    return None, after

def cue_at(c):
    return (c, 1) if isinstance(c, str) else (c["at"], c.get("nth", 1))

def step_cues(toks, cues, beats, accs):
    vt = json.load(open(P("voice-timing.json"), encoding="utf-8"))
    voice_end = round(vt["total"], 3)
    total = round(voice_end + END_HOLD, 2)
    named = {}
    def resolve(c, what):
        ph, nth = cue_at(c)
        t, _ = find(toks, ph, nth, what=what)
        if t is not None:
            named[ph] = round(t, 3)
        return t
    chapters = [t for t in (resolve(c, "chapters") for c in cues.get("chapters", [])) if t is not None]
    if chapters != sorted(chapters):
        problems.append("chapters are not in spoken order; the camera whips will look random. Reorder them.")
    big = [t for t in (resolve(c, "big_moves") for c in cues.get("big_moves", [])) if t is not None]
    slams = []
    for s in cues.get("slams", []):
        t = resolve(s, "slams")
        if t is not None:
            slams.append({"t": round(t, 3), "letter": s.get("letter", "!"), "word": s.get("word", "")})
    tags = []
    for s in cues.get("tags", []):
        t = resolve(s, "tags")
        if t is not None:
            tags.append({"t": round(t, 3), "text": s["text"], "hold": float(s.get("hold", 2.5))})
    payoff = resolve(cues["payoff"], "payoff") if cues.get("payoff") else None
    sfx = []
    for s in cues.get("sfx", []):
        t = resolve(s, "sfx")
        if t is not None:
            sfx.append(dict(s, t=t))
    data = {"total": total, "voiceEnd": voice_end, "beats": beats, "acc": accs, "chapters": [round(c, 3) for c in chapters],
            "bigMoves": [round(b, 3) for b in big], "slams": slams, "tags": tags, "payoff": payoff, "named": named,
            "words": [{"w": t["w"], "s": round(t["s"], 3), "e": round(t["e"], 3)} for t in toks]}
    open(P("assets", "cues.js"), "w", encoding="utf-8").write(
        "/* GENERATED by tools/build.py from cues.json + the voice. Do not edit. */\nwindow.FILM_CUES = " + json.dumps(data) + ";\n")

    # hud.html
    hook = cues.get("hook", {}); endc = cues.get("end", {})
    hook_end = min(chapters[0] if chapters else 3.0, 3.2)
    rows = [f'    <div id="hud-hook" class="clip" data-start="0" data-duration="{round(hook_end, 3)}" data-track-index="3">'
            f'<span class="hud-line"><span id="hud-hook-a">{html.escape(hook.get("line1", ""))}</span></span>'
            f'<span class="hud-line"><span id="hud-hook-b" class="acc">{html.escape(hook.get("line2", ""))}</span></span></div>']
    end_start = round(max(0, voice_end - 0.15), 3)
    rows.append(f'    <div id="hud-end" class="clip" data-start="{end_start}" data-duration="{round(total - end_start, 3)}" data-track-index="3">'
                f'<span class="hud-line"><span id="hud-end-a">{html.escape(endc.get("line1", ""))}</span></span>'
                f'<span class="hud-line"><span id="hud-end-b" class="acc">{html.escape(endc.get("line2", ""))}</span></span></div>')
    for i, s in enumerate(slams):
        st = round(max(0, s["t"] - 0.08), 3)
        rows.append(f'    <div id="hud-slam-{i}" class="clip hud-slamhost" data-start="{st}" data-duration="1.25" data-track-index="4">'
                    f'<div class="hud-slam" id="hud-slam-{i}-in"><span class="hud-slam-letter">{html.escape(s["letter"])}</span>'
                    f'<span class="hud-slam-word">{html.escape(s["word"])}</span></div></div>')
    for i, s in enumerate(tags):
        rows.append(f'    <div id="hud-tag-{i}" class="clip hud-taghost" data-start="{round(s["t"], 3)}" data-duration="{round(s["hold"], 3)}" data-track-index="2">'
                    f'<div id="hud-tag-{i}-in" class="hud-tag">{html.escape(s["text"])}</div></div>')
    rows.append(f'    <div id="hud-flash" class="clip" data-start="0" data-duration="{total}" data-track-index="5"><div id="hud-flash-in"></div></div>')
    open(P("compositions", "hud.html"), "w", encoding="utf-8").write(HUD_HTML.replace("%ROWS%", "\n".join(rows)))

    # index.html lengths
    s = open(P("index.html"), encoding="utf-8").read()
    s = re.sub(r'(<[^>]*data-film-length[^>]*>)', lambda m: re.sub(r'data-duration="[^"]*"', f'data-duration="{total}"', m.group(1)), s)
    s = re.sub(r'(<audio id="voice"[^>]*?)data-duration="[^"]*"', rf'\g<1>data-duration="{voice_end}"', s)
    open(P("index.html"), "w", encoding="utf-8").write(s)
    print(f"3. Cues     : {len(chapters)} chapters, {len(slams)} slams, {len(tags)} name tags, {len(sfx)} sound cues; video = {total}s")
    return data, sfx, big, payoff, total

# ------------------------------------------------------------------ 4. sound
def step_sound(data, sfx, big, payoff, total):
    import numpy as np
    lib = load_json("assets/sfx/sounds.json")
    cache, used = {}, {}
    bed = np.zeros((int((total + 1) * SR), 2), dtype=np.float32)
    def load(name, semis, lp):
        key = (name, semis, lp)
        if key not in cache:
            af = f"asetrate={SR * 2 ** (semis / 12):.0f},aresample={SR},lowpass=f={lp},lowpass=f={lp}"
            raw = subprocess.run(["ffmpeg", "-v", "error", "-i", P("assets", "sfx", name + ".mp3"), "-af", af, "-f", "f32le", "-ac", "2", "-ar", str(SR), "-"],
                                 capture_output=True).stdout
            x = np.frombuffer(raw, dtype=np.float32).reshape(-1, 2).copy()
            if len(x) == 0:
                die(f"could not decode assets/sfx/{name}.mp3 (is ffmpeg installed?)")
            cache[key] = x * (0.8 / (float(np.max(np.abs(x))) or 1))
        return cache[key]
    def place(name, t, gain, semis=0.0, max_len=None, fade_in=0.0, count=True):
        if name not in lib or name.startswith("_"):
            problems.append(f'sound "{name}" is not in assets/sfx/sounds.json; skipped. Pick one from that list.')
            return
        if count:
            used[name] = used.get(name, 0) + 1
        a = load(name, semis, lib[name]["lp"])
        if max_len:
            a = a[: int(max_len * SR)].copy()
            f = min(len(a), int(0.2 * SR)); a[-f:] *= np.linspace(1, 0, f)[:, None]
        if fade_in:
            a = a.copy(); f = min(len(a), int(fade_in * SR)); a[:f] *= np.linspace(0, 1, f)[:, None]
        i0 = int(round((t + FRAME - lib[name]["peak"] / 2 ** (semis / 12)) * SR))
        if i0 < 0:
            a = a[-i0:]; i0 = 0
        i1 = min(len(bed), i0 + len(a))
        if i1 > i0:
            bed[i0:i1] += a[: i1 - i0] * gain
    AIR = [("whoosh", 0, 0.36), ("swoosh", 0, 0.32), ("swish", 2, 0.3), ("whoosh", -3, 0.36), ("swoosh", -2, 0.32), ("swish", -1, 0.3), ("whoosh", 2, 0.36)]
    for i, t in enumerate(data["chapters"]):
        n, st, g = AIR[i % len(AIR)]
        place(n, t, g, semis=st, count=False)
    for t in big:
        place("whoosh-cinematic", t + 0.2, 0.36, max_len=3.4, count=False)
    for i, s in enumerate(data["slams"]):
        place("tom", s["t"], 0.42, semis=[0, -2, -4][i % 3], count=False)
        place("impact-bass-2" if i % 2 else "impact-bass-1", s["t"], 0.5, count=False)
    for s in data["tags"]:
        place("pop", s["t"], 0.3, semis=3, count=False)
    if payoff is not None:
        place("riser", payoff, 0.28, max_len=3.6, fade_in=0.8, count=False)
        place("impact-bass-1", payoff, 0.62, count=False)
    for s in sfx:
        if "run" in s:  # a rising run of notes, e.g. "run": [0, 3, 7]
            for j, st in enumerate(s["run"]):
                place(s["sound"], s["t"] + j * s.get("step", 0.09), s.get("gain", 0.28), semis=st, count=(j == 0))
        else:
            place(s["sound"], s["t"] + s.get("offset", 0), s.get("gain", 0.3), semis=s.get("semis", 0), max_len=s.get("max_len"))
    for n, c in used.items():
        if c > 6:
            problems.append(f'sound "{n}" is used {c} times; the limit is about 6. Swap some for other sounds in sounds.json.')
    pk = float(np.max(np.abs(bed)))
    if pk > 0.89:
        bed *= 0.89 / pk
    with wave.open(P("assets", "sfx", "sfx-bed.wav"), "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((np.clip(bed, -1, 1) * 32767).astype("<i2").tobytes())
    print(f"4. Sound    : sfx-bed.wav written ({len(data['chapters'])} section whooshes + {sum(used.values())} story sounds)")

